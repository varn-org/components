-- the base url variable follows the slug for every provider, so an override is always named after it
local function baseUrlEnv(slug)
    return slug:upper():gsub("[%-%.]", "_") .. "_API_BASE"
end

for _, entry in ipairs(openaiCompatible) do
    local slug = entry[1]
    providers[slug] = {
        adapter = "openai",
        baseUrl = entry[2],
        baseUrlEnv = baseUrlEnv(slug),
        apiKeyEnv = { entry[3], entry[4] },
    }
end

-- these adapters derive their endpoint from the region or project on the request, so an absent base url is not a misconfiguration
local derivesEndpoint = {
    vertex_ai = true,
    vertex_ai_beta = true,
    bedrock = true,
    sagemaker = true,
    sagemaker_chat = true,
}

for _, entry in ipairs(native) do
    local slug = entry[1]
    providers[slug] = {
        adapter = entry[2],
        baseUrl = entry[3],
        baseUrlEnv = baseUrlEnv(slug),
        apiKeyEnv = { entry[4], entry[5] },
        derivesEndpoint = derivesEndpoint[slug] == true,
    }
end

return providers
